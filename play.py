def main():
    sys.stdout.write(HIDE_CURSOR)
    sys.stdout.flush()
    try:
        # Loop the movie twice so it isn't gone in a blink
        for _ in range(1):
            for delay, frame in FRAMES:
                sys.stdout.write(CLEAR)
                sys.stdout.write(frame)
                sys.stdout.flush()
                time.sleep(delay)
        sys.stdout.write("\n")
    except KeyboardInterrupt:
        pass
    finally:
        sys.stdout.write(SHOW_CURSOR)
        sys.stdout.flush()


if __name__ == "__main__":
    main()
